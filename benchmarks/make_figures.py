"""Generate the report's data figures from the results artifact.

    python -m benchmarks.make_figures

Every figure in ``report/figures/`` that carries data is written by this script
from ``report/benchmark_results.tsv`` (and the older ``validation_results.tsv``
freeze, for the one figure that summarizes it). Nothing is retyped, so a figure
cannot disagree with the table beside it: regenerate the artifact, rerun this, and
the PDF follows. A lookup that finds no row raises rather than silently plotting a
gap.

Each file holds one ``tikzpicture`` and no caption -- the report supplies captions,
labels and placement, because those are prose decisions. The shared styles the
files reference live in ``report/figures/i3pw-viz.tex``, which is hand-written.

Two conventions the figures follow throughout, both of them arguments the rest of
the repository makes in words:

* a quantity that was a calibration constraint is never plotted. Constrained
  moments match by construction, so a bar at zero would be an assertion that the
  method works, made by an identity. Those numbers live in the tables, flagged.
* the oracle -- weights built from the true inclusion probabilities -- is drawn in
  neutral ink with an open marker, because it is not a competitor. It is the Monte
  Carlo floor at this sample size, and the distance between it and an estimator is
  the part of the error that better statistics could remove.
"""

