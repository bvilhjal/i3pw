class Results:
    """Indexed access to a results TSV, strict about missing rows."""

    def __init__(self, path: Path = RESULTS_TSV) -> None:
        self.rows = read_tsv(path)
        self.index = {
            (r["benchmark"], r["condition"], r["estimator"], r["metric"]): r
            for r in self.rows
        }
        self.path = path

    def get(self, benchmark: str, condition: str, estimator: str, metric: str) -> dict:
        try:
            return self.index[(benchmark, condition, estimator, metric)]
        except KeyError as exc:
            raise KeyError(
                f"{self.path.name} has no row for "
                f"({benchmark}, {condition!r}, {estimator!r}, {metric!r})"
            ) from exc

    def mean(self, *key) -> float:
        return float(self.get(*key)["mean"])

    def sd(self, *key) -> float:
        value = self.get(*key)["sd"]
        return 0.0 if value is None else float(value)

    def mcse(self, *key) -> float:
        value = self.get(*key)["mcse"]
        return 0.0 if value is None else float(value)

    def conditions(self, benchmark: str) -> list[str]:
        """Conditions of one benchmark, in the order the generator wrote them."""
        seen: list[str] = []
        for row in self.rows:
            if row["benchmark"] == benchmark and row["condition"] not in seen:
                seen.append(row["condition"])
        return seen


# --------------------------------------------------------------------------------
# pgfplots emitters
# --------------------------------------------------------------------------------

def _fmt(value: float) -> str:
    if not np.isfinite(value):
        raise ValueError("cannot plot a non-finite coordinate")
    return f"{value:.6g}"


def axis(options: dict[str, str], body: str, *, environment: str = "axis") -> str:
    """One pgfplots axis. Options are emitted in insertion order."""
    rendered = ",\n  ".join(
        key if value is None else f"{key}={value}" for key, value in options.items()
    )
    return (f"\\begin{{{environment}}}[\n  {rendered},\n]\n"
            f"{body}\\end{{{environment}}}\n")


def picture(body: str) -> str:
    return f"\\begin{{tikzpicture}}\n{body}\\end{{tikzpicture}}\n"


def panel(width: str, body: str) -> str:
    """A side-by-side panel of the given width."""
    return f"\\begin{{minipage}}[t]{{{width}}}\n\\centering\n{body}\\end{{minipage}}"


def series(
    style: str,
    points,
    *,
    label: str | None = None,
    errors: bool = False,
    marks_only: bool = True,
    extra: str = "",
) -> str:
    """One ``\\addplot``; ``points`` is ``(x, y)`` or ``(x, y, err)`` when ``errors``."""
    options = [style]
    if marks_only:
        options.append("only marks")
    if extra:
        options.append(extra)
    if label is None:
        options.append("forget plot")
    if errors:
        # Last: `viz bars` switches the pgfkeys path to `error bars/`, and anything
        # after it is looked up there and rejected.
        options.append("viz bars")
    coordinates = " ".join(
        f"({_fmt(p[0])},{_fmt(p[1])}) +- (0,{_fmt(p[2])})" if errors
        else f"({_fmt(p[0])},{_fmt(p[1])})"
        for p in points
    )
    out = f"\\addplot[{', '.join(options)}] coordinates {{{coordinates}}};\n"
    if label is not None:
        out += f"\\addlegendentry{{{label}}}\n"
    return out


def hbars(style: str, points, *, bar_width: str = "9pt", extra: str = "") -> str:
    """Horizontal bars: ``points`` are ``(value, y)``."""
    options = [f"xbar, bar width={bar_width}, draw=none, mark=none", style, "forget plot"]
    if extra:
        options.append(extra)
    coordinates = " ".join(f"({_fmt(v)},{_fmt(y)})" for v, y in points)
    return f"\\addplot[{', '.join(options)}] coordinates {{{coordinates}}};\n"


def annotate(x: float, y: float, text: str, *, anchor: str = "south",
             size: str = "tiny", shade: str = "vizInk!70") -> str:
    return (f"\\node[font=\\{size}, text={shade}, anchor={anchor}, inner sep=2pt] "
            f"at (axis cs:{_fmt(x)},{_fmt(y)}) {{{text}}};\n")


def zero_line(xmin: float, xmax: float) -> str:
    """The line an unbiased estimator sits on."""
    return (f"\\draw[vizInk!45, line width=0.6pt] (axis cs:{_fmt(xmin)},0) -- "
            f"(axis cs:{_fmt(xmax)},0);\n")


def offsets(n: int, spread: float = 0.62) -> list[float]:
    """Symmetric horizontal offsets for ``n`` series sharing a categorical tick."""
    if n == 1:
        return [0.0]
    step = spread / (n - 1)
    return [-spread / 2 + i * step for i in range(n)]


def write(name: str, body: str) -> Path:
    FIGURE_DIR.mkdir(parents=True, exist_ok=True)
    path = FIGURE_DIR / name
    path.write_text(HEADER + body, encoding="utf-8")
    return path


