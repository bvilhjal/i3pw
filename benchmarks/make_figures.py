def fig_target_error(res: Results) -> str:
    """B3: how a mis-stated register prevalence propagates."""
    deltas = [c for c in res.conditions("B3_target_error") if c != "reference"]
    x = [float(d) * 100 for d in deltas]

    band, line = [], []
    for d, xi in zip(deltas, x, strict=True):
        mean = res.mean("B3_target_error", d, "ipw+cal", "trait_bias_sd")
        sd = res.sd("B3_target_error", d, "ipw+cal", "trait_bias_sd")
        line.append((xi, mean, sd))
        band.append((xi, mean, sd))
    body_a = zero_line(x[0], x[-1])
    for name, style in (("naive", "viz naive"), ("ipw", "viz ipw")):
        value = res.mean("B3_target_error", "reference", name, "trait_bias_sd")
        body_a += (f"\\addplot[{style}, viz rule, forget plot] coordinates "
                   f"{{({_fmt(x[0])},{_fmt(value)}) ({_fmt(x[-1])},{_fmt(value)})}};\n")
        body_a += annotate(x[-1], value, LABEL[name], anchor="south east")
    body_a += series("viz ipwcal", line, errors=True, marks_only=False)
    body_a += annotate(-32, 0.03, "ipw{+}cal $\\pm$ 1 SD", anchor="south west",
                       shade="vizInk!80")
    axis_a = axis({
        "width": "0.86\\linewidth", "height": "5.4cm", "viz axis": None,
        "title": "{\\textbf{A}\\quad held-out trait mean}",
        "xlabel": "{error in the register prevalence (\\%)}",
        "ylabel": "{bias (population SD)}",
        "xmin": "-34", "xmax": "34", "xtick": "{-30,-20,-10,0,10,20,30}",
    }, body_a)

    prev = [(xi, res.mean("B3_target_error", d, "ipw+cal",
                          "unanchored_prevalence_error_pct"),
             res.sd("B3_target_error", d, "ipw+cal",
                    "unanchored_prevalence_error_pct"))
            for d, xi in zip(deltas, x, strict=True)]
    body_b = zero_line(x[0], x[-1])
    body_b += series("viz ipwcal", prev, errors=True, marks_only=False)
    axis_b = axis({
        "width": "0.86\\linewidth", "height": "5.4cm", "viz axis": None,
        "title": "{\\textbf{B}\\quad second disease}",
        "xlabel": "{error in the register prevalence (\\%)}",
        "ylabel": "{relative error (\\%)}",
        "xmin": "-34", "xmax": "34", "xtick": "{-30,-20,-10,0,10,20,30}",
    }, body_b)

    return (panel("0.485\\textwidth", picture(axis_a)) + "\\hfill%\n"
            + panel("0.485\\textwidth", picture(axis_b)) + "\n")


