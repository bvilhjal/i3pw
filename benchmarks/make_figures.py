def fig_shrinkage(res: Results) -> str:
    """B7: whether relaxing an exact constraint ever pays, and what it costs."""
    conditions = res.conditions("B7_shrinkage")
    laws = ("correct", "base + margin", "misspecified")
    law_style = {"correct": "viz ipwcal", "base + margin": "viz ipw",
                 "misspecified": "viz cal"}
    law_label = dict(zip(laws, laws, strict=True))
    estimator = {"correct": "cal", "base + margin": "ipw+cal", "misspecified": "ipw+cal"}

    def sweep(law: str, metric: str) -> list[tuple[float, float]]:
        out = []
        for c in conditions:
            if not c.startswith(f"{law} | ridge="):
                continue
            ridge = float(c.split("ridge=")[1])
            if ridge == 0.0:
                continue
            out.append((ridge, res.mean("B7_shrinkage", c, estimator[law], metric)))
        return out

    def exact(law: str, metric: str) -> float:
        return res.mean("B7_shrinkage", f"{law} | ridge=0", estimator[law], metric)

    common = {
        "xmode": "log", "xmin": "6e-5", "xmax": "1.6",
        "xtick": "{1e-4,1e-3,1e-2,1e-1,1}",
        "xticklabels": "{$10^{-4}$,$10^{-3}$,$10^{-2}$,$10^{-1}$,$1$}",
        "xlabel": "{ridge on the tilt}",
    }

    body_a = ""
    for law in laws:
        value = exact(law, "trait_rmse_sd")
        body_a += (f"\\addplot[{law_style[law]}, viz rule, forget plot] coordinates "
                   f"{{(6e-5,{_fmt(value)}) (1.6,{_fmt(value)})}};\n")
        body_a += series(law_style[law], sweep(law, "trait_rmse_sd"),
                         marks_only=False, label=law_label[law])
    axis_a = axis({
        "width": "0.86\\linewidth", "height": "5.0cm", "viz axis": None,
        "title": "{\\textbf{A}\\quad RMSE}",
        "ylabel": "{RMSE (population SD)}",
        # Log: the correct arm climbs an order of magnitude, which on a linear axis
        # flattens the two minima this panel exists to show.
        "ymode": "log", "ymin": "0.015", "ymax": "0.35",
        "ytick": "{0.02,0.05,0.1,0.2}", "yticklabels": "{0.02,0.05,0.10,0.20}",
        "legend style": "{at={(0.5,-0.34)}, anchor=north, legend columns=1}",
        **common,
    }, body_a)

    # No legend here: six entries do not fit, colour already means the arm (Panel A
    # says so), and solid-versus-dashed is direct-labelled on the curves.
    body_b = ""
    for law in laws:
        body_b += series(law_style[law], sweep(law, "trait_abs_bias_sd"),
                         marks_only=False)
        sd_points = [
            (ridge, res.sd("B7_shrinkage", f"{law} | ridge={ridge:g}",
                           estimator[law], "trait_bias_sd"))
            for ridge, _ in sweep(law, "trait_abs_bias_sd")
        ]
        body_b += series(law_style[law], sd_points, marks_only=False,
                         extra="densely dashed")
    body_b += annotate(1.4, 0.26, "$|$bias$|$", anchor="north east")
    body_b += annotate(1.4, 0.0125, "SD", anchor="north east")
    axis_b = axis({
        "width": "0.86\\linewidth", "height": "5.0cm", "viz axis": None,
        "title": "{\\textbf{B}\\quad bias and spread}",
        "ylabel": "{population SD}",
        "ymode": "log", "ymin": "0.004", "ymax": "0.4",
        "ytick": "{0.005,0.01,0.02,0.05,0.1,0.2}",
        "yticklabels": "{0.005,0.01,0.02,0.05,0.10,0.20}",
        **common,
    }, body_b)

    body_c = ""
    for law in laws:
        value = exact(law, "kish_ess")
        body_c += (f"\\addplot[{law_style[law]}, viz rule, forget plot] coordinates "
                   f"{{(6e-5,{_fmt(value)}) (1.6,{_fmt(value)})}};\n")
        body_c += series(law_style[law], sweep(law, "kish_ess"), marks_only=False)
    axis_c = axis({
        "width": "0.86\\linewidth", "height": "5.0cm", "viz axis": None,
        "title": "{\\textbf{C}\\quad effective sample size}",
        "ylabel": "{Kish ESS}", "ymin": "1000",
        **common,
    }, body_c)

    return (panel("0.325\\textwidth", picture(axis_a)) + "\\hfill%\n"
            + panel("0.325\\textwidth", picture(axis_b)) + "\\hfill%\n"
            + panel("0.325\\textwidth", picture(axis_c)) + "\n")


