def tab_shrinkage(res: Results) -> str:
    conditions = res.conditions("B7_shrinkage")
    arms, seen = [], set()
    for c in conditions:
        arm = c.split(" | ")[0]
        if arm not in seen:
            seen.add(arm)
            arms.append(arm)
    estimator = {"correct": "cal", "base + margin": "ipw+cal", "misspecified": "ipw+cal"}
    ridges = (0.0, 1e-3, 1e-2, 3e-2, 0.1, 0.3, 1.0)
    header = " & ".join(f"{r:g}" if r else "0 (exact)" for r in ridges)
    rows = [f"Ridge & {header} \\\\\n\\midrule"]
    for arm in arms:
        rows.append(group(f"Specification: {arm}", len(ridges) + 1))
        for metric, name, fmt in (("trait_abs_bias_sd", "$|$bias$|$", ".4f"),
                                  ("trait_rmse_sd", "RMSE", ".4f"),
                                  ("kish_ess", "ESS", ".0f")):
            cells = [format(res.mean("B7_shrinkage", f"{arm} | ridge={r:g}",
                                     estimator[arm], metric), fmt) for r in ridges]
            rows.append(f"\\quad {name} & " + " & ".join(cells) + " \\\\")
    return tabular("l" + "r" * len(ridges), rows)


