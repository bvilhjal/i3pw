def fig_selection_laws(res: Results) -> str:
    """B1: absolute bias and effective sample size across five recruitment laws."""
    laws = res.conditions("B1_selection_law")
    shown = ("naive", "ipw", "cal", "ipw+cal", "oracle")
    xticks = ",".join(str(i) for i in range(len(laws)))
    xlabels = ",".join(f"{{{law}}}" for law in laws)
    shifts = offsets(len(shown))

    body_a = ""
    for method, dx in zip(shown, shifts, strict=True):
        points = [
            (i + dx, abs(res.mean("B1_selection_law", law, method, "trait_bias_sd")))
            for i, law in enumerate(laws)
        ]
        body_a += series(STYLE[method], points, label=LABEL[method])
    axis_a = axis({
        "width": "0.86\\linewidth", "height": "5.6cm", "viz axis": None,
        "title": "{\\textbf{A}\\quad absolute bias}",
        "ylabel": "{$|$bias$|$ (population SD)}",
        "ymode": "log", "ymin": "0.0012", "ymax": "1.4",
        "ytick": "{0.003,0.01,0.03,0.1,0.3,1}",
        "yticklabels": "{0.003,0.01,0.03,0.1,0.3,1}",
        "xmin": "-0.6", "xmax": f"{len(laws) - 0.4}",
        "xtick": f"{{{xticks}}}", "xticklabels": f"{{{xlabels}}}",
        "x tick label style": "{font=\\scriptsize, rotate=20, anchor=east}",
        "legend style": "{at={(0.5,-0.34)}, anchor=north, legend columns=3}",
    }, body_a)

    body_b = ""
    for method, dx in zip(shown, shifts, strict=True):
        points = [
            (i + dx, res.mean("B1_selection_law", law, method, "kish_ess"),
             res.sd("B1_selection_law", law, method, "kish_ess"))
            for i, law in enumerate(laws)
        ]
        body_b += series(STYLE[method], points, errors=True)
    axis_b = axis({
        "width": "0.86\\linewidth", "height": "5.6cm", "viz axis": None,
        "title": "{\\textbf{B}\\quad effective sample size}",
        "ylabel": "{Kish ESS (of ${\\sim}2500$ participants)}",
        "ymin": "800", "ymax": "2700", "ytick": "{1000,1500,2000,2500}",
        "xmin": "-0.6", "xmax": f"{len(laws) - 0.4}",
        "xtick": f"{{{xticks}}}", "xticklabels": f"{{{xlabels}}}",
        "x tick label style": "{font=\\scriptsize, rotate=20, anchor=east}",
    }, body_b)

    return (panel("0.485\\textwidth", picture(axis_a)) + "\\hfill%\n"
            + panel("0.485\\textwidth", picture(axis_b)) + "\n")


